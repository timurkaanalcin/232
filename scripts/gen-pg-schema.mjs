#!/usr/bin/env node
// Converts database/migrations/*.sql (SQLite/D1 dialect) + seed.sql into an
// idempotent PostgreSQL schema module used by the Vercel/Node runtime.
// Usage: node scripts/gen-pg-schema.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const migDir = path.join(root, "database", "migrations");

function stripComments(sql) {
  return sql
    .split("\n")
    .map((line) => line.replace(/--.*$/, "").trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

function convertSchema(sql) {
  return stripComments(sql)
    .replace(/^\s*PRAGMA[^;]*;\s*$/gim, "")
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, "BIGSERIAL PRIMARY KEY")
    .replace(/\bINTEGER\b/g, "BIGINT")
    .replace(/\bREAL\b/g, "DOUBLE PRECISION")
    .replace(/\s+COLLATE NOCASE/g, "")
    .replace(/CREATE TABLE (?!IF NOT EXISTS)/g, "CREATE TABLE IF NOT EXISTS ")
    .replace(/CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)/g, "CREATE $1INDEX IF NOT EXISTS ")
    .replace(/ADD COLUMN (?!IF NOT EXISTS)/g, "ADD COLUMN IF NOT EXISTS ");
}

function convertSeed(sql) {
  return stripComments(sql)
    .replace(/unixepoch\(\)\s*\*\s*1000/g, "(extract(epoch from now()) * 1000)::bigint")
    .replace(/INSERT OR IGNORE INTO([\s\S]*?);/g, "INSERT INTO$1\nON CONFLICT DO NOTHING;");
}

const files = fs.readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort();
const migrations = files.map((name) => ({ name, sql: convertSchema(fs.readFileSync(path.join(migDir, name), "utf8")) }));
const seed = convertSeed(fs.readFileSync(path.join(root, "database", "seed.sql"), "utf8"));

const extra = `CREATE TABLE IF NOT EXISTS rate_limits (
  key      TEXT PRIMARY KEY,
  count    BIGINT NOT NULL,
  reset_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_rate_limits_reset ON rate_limits(reset_at);`;

const out = `// GENERATED by scripts/gen-pg-schema.mjs from database/migrations + seed.sql. Do not edit.
export const PG_MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(
  [...migrations, { name: "9001_rate_limits.sql", sql: extra }],
  null,
  2,
)};

export const PG_SEED_SQL = ${JSON.stringify(seed)};
`;
fs.writeFileSync(path.join(root, "src", "node-runtime", "pg-schema.generated.ts"), out);
console.log(`wrote ${migrations.length + 1} migrations`);
