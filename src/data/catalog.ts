function inspectionFor(seed: number, technician: string): InspectionReport {
  const items: InspectionItem[] = INSPECTION_TEMPLATE.map(([category, name], index) => {
    const roll = (seed + index * 17) % 23;
    if (roll === 0) return { category, name, status: "attention", note: "Kontrol önerilir" };
    if (roll === 1 && index % 11 === 0) return { category, name, status: "attention", note: "Hafif iz" };
    return { category, name, status: "pass" };
  });
  const attention = items.filter((i) => i.status !== "pass").length;
  const score = Math.max(86, 100 - attention * 3);
  return {
    score,
    inspectedAt: Date.UTC(2026, 7, 12 + (seed % 20)),
    technician,
    items,
  };
}

function featuresFor(seed: number, extras: string[] = []): string[] {
  const picked = FEATURE_POOL.filter((_, i) => (seed + i) % 3 !== 0).slice(0, 10);
  return Array.from(new Set([...picked, ...extras]));
}

